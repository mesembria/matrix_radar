def text_w(s):
    return len(s) * 4 - 1 if s else 0


def draw_text(bmp, x, y, s, c):
    for ch in s.upper():
        g = GLYPHS.get(ch)
        if g:
            for i in range(15):
                if g[i] == "1":
                    px, py = x + i % 3, y + i // 3
                    if 0 <= px < 64 and 0 <= py < 32:
                        bmp[px, py] = c
        x += 4
